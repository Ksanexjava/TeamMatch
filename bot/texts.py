def profile_card(p: dict, show_contact: bool = False) -> str:
    """Карточка анкеты для показа. Контакт показываем только своей анкете и при мэтче."""
    lines = [f"👤 {p.get('name') or 'Без имени'}"]
    study = p.get("university") or ""
    if p.get("course"):
        study = f"{study}, {p['course']} курс" if study else f"{p['course']} курс"
    if study:
        lines.append(f"🎓 {study}")
    if p.get("city"):
        lines.append(f"📍 {p['city']}")
    if p.get("role"):
        lines.append(f"🛠 Роль: {p['role']}")
    if p.get("looking_for"):
        lines.append(f"🎯 Ищет: {p['looking_for']}")
    if p.get("interests"):
        lines.append("💡 Интересы: " + ", ".join(p["interests"]))
    if p.get("about"):
        lines.append(f"\n{p['about']}")
    if p.get("github"):
        lines.append(f"🔗 {p['github']}")
    if show_contact and p.get("username"):
        lines.append(f"✉️ Контакт: {p['username']}")
    return "\n".join(lines)
